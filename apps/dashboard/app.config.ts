import {
  APPS,
  ENVIRONMENTS,
  appNameFor,
  bundleIdFor,
  schemeFor,
  type Environment,
} from "@hagz/contracts";
import type { ExpoConfig } from "expo/config";

// Built once per environment (APP_ENV), so staging and production install side by side. Links Hagz
// sends (@hagz/contracts links.ts) are https URLs on the web app's domain (WEB_URL): iOS and Android
// open them in this app once the domain is verified (the web app serves the verification files).
const env = (process.env.APP_ENV ?? "development") as Environment;
if (!ENVIRONMENTS.includes(env)) throw new Error(`Unknown APP_ENV: ${env}`);
const webHost = process.env.WEB_URL ? new URL(process.env.WEB_URL).host : undefined;

const config: ExpoConfig = {
  name: appNameFor("dashboard", env),
  slug: "hagz-dashboard",
  version: "0.0.0",
  orientation: "portrait",
  userInterfaceStyle: "automatic",
  // Generated by @hagz/brand (pnpm --filter @hagz/brand generate): white and electric blue.
  icon: "./assets/icon.png",
  scheme: schemeFor("dashboard", env),
  ios: {
    bundleIdentifier: bundleIdFor("dashboard", env),
    associatedDomains: webHost ? [`applinks:${webHost}`] : [],
    // Google Maps on iOS, which is what people here read: it needs the Google Maps SDK compiled
    // in, so it only applies to builds. Expo Go has Apple Maps and falls back to it.
    ...(process.env.GOOGLE_MAPS_IOS_KEY
      ? { config: { googleMapsApiKey: process.env.GOOGLE_MAPS_IOS_KEY } }
      : {}),
  },
  android: {
    package: bundleIdFor("dashboard", env),
    // Android maps are Google's, with a key of its own in builds (Expo Go brings its own). Left
    // out when unset so builds still work.
    ...(process.env.GOOGLE_MAPS_ANDROID_KEY
      ? { config: { googleMaps: { apiKey: process.env.GOOGLE_MAPS_ANDROID_KEY } } }
      : {}),
    adaptiveIcon: {
      foregroundImage: "./assets/adaptive-icon.png",
      monochromeImage: "./assets/adaptive-icon-monochrome.png",
      backgroundColor: "#FFFFFF",
    },
    intentFilters: webHost
      ? [
          {
            action: "VIEW",
            autoVerify: true,
            data: [{ scheme: "https", host: webHost, pathPrefix: APPS.dashboard.pathPrefix }],
            category: ["BROWSABLE", "DEFAULT"],
          },
        ]
      : [],
  },
  plugins: [
    "expo-router",
    "expo-dev-client",
    "expo-secure-store",
    "expo-status-bar",
    // Held while the app decides where it opens (src/lib/boot.ts): the staff logo on white.
    [
      "expo-splash-screen",
      { image: "./assets/adaptive-icon.png", imageWidth: 160, backgroundColor: "#FFFFFF" },
    ],
    // Builds lay Arabic out right-to-left natively (I18nManager); Screen sets Yoga's direction too.
    ["expo-localization", { supportsRTL: true, supportedLocales: ["en", "ar"] }],
    // Only to centre the map on the owner while they place their venue's pin; never in the
    // background, and the venue's pin is the only thing kept.
    [
      "expo-location",
      {
        locationWhenInUsePermission:
          "Hagz uses your location to centre the map while you place your venue.",
        isAndroidBackgroundLocationEnabled: false,
      },
    ],
  ],
  experiments: {
    typedRoutes: true,
  },
};

export default config;
