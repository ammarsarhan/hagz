// The public site's words in English and Arabic. The Arabic is the customer app's
// (apps/customer/src/i18next/locales/ar.ts) wherever the app says the same thing: keep them saying
// the same things. Arabic uses Western digits, as the apps do.

export type Locale = "en" | "ar";

export const dirOf = (locale: Locale) => (locale === "ar" ? "rtl" : "ltr");

// The Intl locale: Arabic as written in Egypt, with Western digits.
export const intlTag = (locale: Locale) => (locale === "ar" ? "ar-EG-u-nu-latn" : "en-GB");

// The same page in a language: English at the root, Arabic under /ar.
export const pathIn = (locale: Locale, path: string) => (locale === "ar" ? `/ar${path}` : path);

type Forms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string };

// The form for a count, with {n} filled in. Arabic has six (zero, one, two, few, many, other).
export const plural = (locale: Locale, count: number, forms: Forms) =>
  (forms[new Intl.PluralRules(locale).select(count)] ?? forms.other).replaceAll(
    "{n}",
    String(count),
  );

